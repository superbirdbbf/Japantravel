let selected = 0;
const tabs = document.querySelector("#day-tabs");
const content = document.querySelector("#day-content");

function renderDay() {
  tabs.innerHTML = days
    .map(
      (day, index) =>
        `<button class="day-tab ${index === selected ? "active" : ""}" data-i="${index}">D${index + 1}<br><small>${day.date}</small></button>`,
    )
    .join("");

  const day = days[selected];
  content.innerHTML = `
    <article class="day-card">
      <div class="day-meta">
        <div class="day-number">0${selected + 1}</div>
        <div class="day-date">${day.date}</div>
        <div class="day-place">${day.place}</div>
      </div>
      <div class="timeline">
        ${day.events
          .map(
            ([time, detail, route]) => `
              <div class="event">
                <div class="event-time">${time}</div>
                <div class="event-detail">${detail}<div class="event-route">${route}</div></div>
              </div>`,
          )
          .join("")}
      </div>
    </article>`;

  tabs.querySelectorAll("button").forEach((button) => {
    button.onclick = () => {
      selected = Number(button.dataset.i);
      renderDay();
    };
  });
}

function renderSpots(query = "") {
  const normalizedQuery = query.trim().toLowerCase();
  const list = spots.filter((spot) =>
    spot.join(" ").toLowerCase().includes(normalizedQuery),
  );

  document.querySelector("#spots").innerHTML = list
    .map(
      ([city, name, description]) => `
        <article class="spot-card">
          <span class="spot-tag">${city}</span>
          <div><h3>${name}</h3><p>${description}</p></div>
        </article>`,
    )
    .join("");
}

document.querySelector("#search").oninput = (event) =>
  renderSpots(event.target.value);

renderDay();
renderSpots();
